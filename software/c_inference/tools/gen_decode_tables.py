#!/usr/bin/env python3
"""Generate decode_tables.h (integer decode look-up tables) from <model>/layers.json.

The raw yolo inputs are int8 with 2^-fa_in scale, so sigmoid and exp only ever see 256 distinct
values.  Everything the decode needs is therefore a 256-entry table (Q16 fixed point):
  SIG[n][i]      = sigmoid(v)                       v = (i-128) / 2^fa_in
  EXPW[n][a][i]  = exp(v) * anchor_w[mask[a]] / net_w   (Q20, clamped to 64.0)
  EXPH[n][a][i]  = exp(v) * anchor_h[mask[a]] / net_h   (Q20)
Probabilities are Q16 (65536 = 1.0); box sizes are Q20 (1048576 = 1.0) so thin boxes keep precision.
Table index = raw int8 value + 128.
usage: gen_decode_tables.py <model_dir/layers.json> <out decode_tables.h>
"""
import json
import math
import sys

def q(x, bits, clamp):
    return min(int(math.floor(x * (1 << bits) + 0.5)), clamp)


def q16(x):
    return q(x, 16, 1 << 16)


def q20(x):
    return q(x, 20, 64 << 20)             # 64.0 max: keeps w*h*100 inside int64 in the NMS


def main(src, dst):
    j = json.load(open(src))
    _, net_h, net_w = j['input']
    ys = [l for l in j['layers'] if l['type'] == 'yolo']
    assert ys, 'no yolo layers in layers.json'
    classes = ys[0]['classes']
    na = len(ys[0]['mask'])
    assert all(len(y['mask']) == na and y['classes'] == classes for y in ys)
    o = ['/* auto-generated by gen_decode_tables.py -- do not edit */',
         '#ifndef DECODE_TABLES_H', '#define DECODE_TABLES_H', '#include <stdint.h>', '',
         '#define DEC_NYOLO   %d' % len(ys), '#define DEC_NA      %d' % na,
         '#define DEC_CLASSES %d' % classes, '#define DEC_K       %d  /* 5 + classes */' % (5 + classes), '',
         '/* raw (pre-activation) output of each yolo layer = output of layer DEC_SRC[n] */',
         'static const uint16_t DEC_SRC[DEC_NYOLO] = {%s};' % ', '.join(str(y['idx'] - 1) for y in ys),
         'static const uint16_t DEC_GRID_W[DEC_NYOLO] = {%s};' % ', '.join(str(y['w_in']) for y in ys),
         'static const uint16_t DEC_GRID_H[DEC_NYOLO] = {%s};' % ', '.join(str(y['h_in']) for y in ys), '']
    sig, ew, eh = [], [], []
    for y in ys:
        fa = y['fa_in']
        vals = [(i - 128) / float(1 << fa) for i in range(256)]
        sig.append([q16(1.0 / (1.0 + math.exp(-v))) for v in vals])
        aw = [[q20(math.exp(min(v, 40.0)) * y['anchors'][2 * m] / net_w) for v in vals] for m in y['mask']]
        ah = [[q20(math.exp(min(v, 40.0)) * y['anchors'][2 * m + 1] / net_h) for v in vals] for m in y['mask']]
        ew.append(aw)
        eh.append(ah)

    def arr(name, dims, data):
        o.append('static const uint32_t %s%s = {' % (name, dims))
        o.append(data)
        o.append('};')
        o.append('')

    def row(v):
        return '{' + ','.join(map(str, v)) + '}'
    arr('DEC_SIG', '[DEC_NYOLO][256]', ',\n'.join(row(s) for s in sig))
    arr('DEC_EXPW', '[DEC_NYOLO][DEC_NA][256]', ',\n'.join('{' + ',\n'.join(row(a) for a in n) + '}' for n in ew))
    arr('DEC_EXPH', '[DEC_NYOLO][DEC_NA][256]', ',\n'.join('{' + ',\n'.join(row(a) for a in n) + '}' for n in eh))
    o.append('#endif')
    open(dst, 'w').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
